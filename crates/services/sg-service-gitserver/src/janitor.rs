    #[test]
    fn needs_maintenance_reasons() {
        let tmp = tmpdir();
        let check = |dir: &Path| needs_maintenance(dir, 50, 1024);
        // No bitmap.
        assert!(check(tmp.path()).0);
        assert_eq!(check(tmp.path()).1, "bitmap");

        let pack = tmp.path().join("objects").join("pack");
        std::fs::create_dir_all(&pack).expect("mkdir");
        std::fs::write(pack.join("a.bitmap"), b"").expect("write");
        assert_eq!(check(tmp.path()).1, "commit_graph");

        let info = tmp.path().join("objects").join("info");
        std::fs::create_dir_all(&info).expect("mkdir");
        std::fs::write(info.join("commit-graph"), b"").expect("write");
        assert_eq!(check(tmp.path()).1, "skipped");

        // More packfiles than the limit.
        for name in ["b.pack", "c.pack"] {
            std::fs::write(pack.join(name), b"").expect("write");
        }
        assert_eq!(needs_maintenance(tmp.path(), 1, 1024).1, "packfiles");
        // More loose objects than the limit (1 * 256 > 255).
        let loose = tmp.path().join("objects").join("17");
        std::fs::create_dir_all(&loose).expect("mkdir");
        std::fs::write(loose.join("ab"), b"").expect("write");
        assert_eq!(needs_maintenance(tmp.path(), 2, 255).1, "loose_objects");
    }

    #[test]
    fn locks_gc_exclusively() {
        let tmp = tmpdir();
        let (first, error) = lock_repo_for_gc(tmp.path());
        assert!(error.is_none());
        assert!(first.is_some());
        let content = std::fs::read_to_string(tmp.path().join(GC_LOCK_FILE)).expect("read");
        assert!(content.starts_with(&format!("{} ", std::process::id())));

        let (second, error) = lock_repo_for_gc(tmp.path());
        assert!(second.is_none());
        let message = error.expect("locked").message();
        assert!(
            message.contains("is already running a gc operation"),
            "{message}"
        );
        drop(first);
        std::fs::remove_file(tmp.path().join(GC_LOCK_FILE)).expect("unlock");
        assert!(lock_repo_for_gc(tmp.path()).0.is_some());
    }

    fn bare_repo(root: &Path, name: &str) -> (String, PathBuf) {
        let git_dir = root.join(name).join(".git");
        std::fs::create_dir_all(&git_dir).expect("mkdir");
        let status = std::process::Command::new("git")
            .args(["init", "--bare", "-q", git_dir.to_str().unwrap()])
            .status()
            .expect("git init --bare");
        assert!(status.success());
        (name.to_owned(), git_dir)
    }

    async fn janitor(repos_dir: &Path, addresses: GitserverAddresses) -> Janitor {
        let mut env = EnvReader::new();
        let config = JanitorConfig::load(&mut env, Duration::from_secs(60), false);
        Janitor {
            repos_dir: Arc::new(repos_dir.to_path_buf()),
            store: None,
            shard_id: "gitserver-0".to_owned(),
            addresses,
            long_command_timeout: Duration::from_secs(7200),
            disable_auto_git_updates: false,
            config: JanitorConfig {
                git_gc_mode: GcMode::GitAutoGc,
                ..config
            },
        }
    }

