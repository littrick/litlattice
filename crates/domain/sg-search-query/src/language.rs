//! Language-name/alias lookup for `validate.isLanguage`.
//!
//! `lib/codeintel/languages.GetLanguageByNameOrAlias` normalizes the value with
//! `convertToAliasKey` (part before the first comma, spaces to underscores,
//! lowered) and looks it up in go-enry's `LanguageByAliasMap`, after first
//! checking `unsupportedByEnryAliasMap` (Apex/Magik/Pkl). `validate.isLanguage`
//! only observes the `ok` result, so the table below stores the accepted keys
//! verbatim from the vendored enry data at the Go baseline commit.

/// `convertToAliasKey`.
pub fn convert_to_alias_key(name: &str) -> String {
    let name = name.split(',').next().unwrap_or("");
    name.replace(' ', "_").to_lowercase()
}

/// `languages.GetLanguageByNameOrAlias` returns `ok` for these keys.
pub fn is_valid_language(name_or_alias: &str) -> bool {
    let key = convert_to_alias_key(name_or_alias);
    LANGUAGE_ALIAS_KEYS.binary_search(&key.as_str()).is_ok()
}

