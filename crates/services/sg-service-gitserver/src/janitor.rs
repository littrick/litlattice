/// `sgMaintenanceScript`, embedded like `//go:embed sg_maintenance.sh`.
const SG_MAINTENANCE_SCRIPT: &str = include_str!("sg_maintenance.sh");

/// `gcFailureRecloneThreshold`: failed `git gc` runs before a reclone.
const GC_FAILURE_RECLONE_THRESHOLD: i64 = 5;
/// The log file `sg maintenance` leaves behind after a failure.
const SGM_LOG: &str = "sgm.log";
const SGM_LOG_PREFIX: &str = "failed=";
const SGM_LOG_HEADER: &str = "DO NOT EDIT: generated by gitserver.
This file records the number of failed runs of sg maintenance and the
last error message. The number of failed attempts is compared to the
number of allowed retries (see SRC_SGM_RETRIES) to decide whether a
repository should be recloned.";
/// `gcLockFile`: owned by `git gc` and `sg maintenance`.
const GC_LOCK_FILE: &str = "gc.pid";
/// `lastSizeCalculationFilepath`.
const LAST_SIZE_CALCULATION: &str = ".sourcegraph-last-size-calculation";
/// `gcFailedCounterFilepath`.
const GC_FAILED_COUNTER: &str = ".sourcegraph-gc-fail-counter";
/// `gitcli.RepoMaybeCorruptFlagFilepath`.
const MAYBE_CORRUPT_FLAG: &str = ".sourcegraph-maybe-corrupt-repo";
/// `repoSizeRecalcInterval`: recompute a repository's size at most daily.
const REPO_SIZE_RECALC_INTERVAL: Duration = Duration::from_secs(24 * 60 * 60);
const DEFAULT_SGM_LOG_EXPIRE: Duration = Duration::from_secs(24 * 60 * 60);

/// `JanitorConfig` plus the package-level `cleanup.go` settings.
#[derive(Debug, Clone)]
pub struct JanitorConfig {
    pub interval: Duration,
    pub disable_delete_repos_on_wrong_shard: bool,
    pub remove_non_existing_repos: bool,
    pub git_gc_mode: GcMode,
    pub auto_pack_limit: i64,
    pub loose_objects_limit: i64,
    pub sgm_log_expire: Duration,
    pub sgm_retries: i64,
}

impl JanitorConfig {
    /// Read the `cleanup.go` package-level environment variables. The
    /// baseline registers these at package init (`env.Get` / `Atoi`), so they
    /// are startup snapshots.
    pub fn load(
        env: &mut EnvReader,
        interval: Duration,
        disable_delete_repos_on_wrong_shard: bool,
    ) -> Self {
        // `strconv.Atoi` failures fall back to 0, like the baseline.
        let auto_pack_limit = env
            .get(
                "SRC_GIT_AUTO_PACK_LIMIT",
                "50",
                "the maximum number of pack files we tolerate before we trigger a repack",
            )
            .parse()
            .unwrap_or(0);
        let loose_objects_limit = env
            .get(
                "SRC_GIT_LOOSE_OBJECTS_LIMIT",
                "1024",
                "the maximum number of loose objects we tolerate before we trigger a repack",
            )
            .parse()
            .unwrap_or(0);
        // `env.MustGetDuration` would panic on an invalid value; falling back
        // to the default keeps the server usable instead of aborting startup.
        let sgm_log_expire = crate::memobs::parse_go_duration(&env.get(
            "SRC_GIT_LOG_FILE_EXPIRY",
            "24h0m0s",
            "the number of hours after which sg maintenance runs even if a log file is present",
        ))
        .unwrap_or(DEFAULT_SGM_LOG_EXPIRE);
        let sgm_retries = env
            .get(
                "SRC_SGM_RETRIES",
                "3",
                "the maximum number of times we retry sg maintenance before triggering a reclone.",
            )
            .parse()
            .unwrap_or(0);
        let remove_non_existing_repos = crate::memobs::parse_go_bool(&env.get(
            "SRC_REMOVE_NON_EXISTING_REPOS",
            "false",
            "controls if gitserver cleanup tries to remove repos from disk which are not defined in the DB",
        ))
        .unwrap_or(false);

        Self {
            interval,
            disable_delete_repos_on_wrong_shard,
            remove_non_existing_repos,
            git_gc_mode: postfetch::gc_mode(),
            auto_pack_limit,
            loose_objects_limit,
            sgm_log_expire,
            sgm_retries,
        }
    }
}

/// `NewJanitor`: the periodic cleanup job.
pub struct Janitor {
    pub repos_dir: Arc<PathBuf>,
    pub store: Option<Arc<GitserverReposStore>>,
    pub shard_id: String,
    pub addresses: GitserverAddresses,
    pub long_command_timeout: Duration,
    pub disable_auto_git_updates: bool,
    pub config: JanitorConfig,
}

/// Counters shared by the cleanup jobs of one run (`cleanupRepos`' closures).
#[derive(Default)]
struct RunState {
    repo_to_size: Vec<(String, i64)>,
    wrong_shard_count: i64,
    wrong_shard_deleted: i64,
    known_shard: bool,
}

/// `(done, err)`: `done` means the repository was removed and no further jobs
/// should run for it.
type Outcome = (bool, Option<GitError>);

impl Janitor {
    /// `goroutine.NewPeriodicGoroutine`: run immediately, then every interval
    /// until the service shuts down.
    pub async fn run(&self, shutdown: CancellationToken) {
        loop {
            if shutdown.is_cancelled() {
                return;
            }
            tracing::info!("Starting janitor run");
            self.cleanup_repos(&shutdown).await;
            tokio::select! {
                _ = shutdown.cancelled() => return,
                _ = tokio::time::sleep(self.config.interval) => {}
            }
        }
    }

    /// `cleanupRepos`.
    pub async fn cleanup_repos(&self, shutdown: &CancellationToken) {
        struct RunGuard {
            start: Instant,
        }
        impl Drop for RunGuard {
            fn drop(&mut self) {
                metrics::janitor_running(false);
                metrics::janitor_duration(self.start.elapsed().as_secs_f64());
            }
        }

        let start = Instant::now();
        metrics::janitor_running(true);
        let _guard = RunGuard { start };

        let mut state = RunState {
            known_shard: self
                .addresses
                .addresses
                .iter()
                .any(|addr| crate::addrs::hostname_match(&self.shard_id, addr)),
            ..RunState::default()
        };
        if !state.known_shard {
            tracing::warn!(
                current_hostname = %self.shard_id,
                all_shards = ?self.addresses.addresses,
                "current shard is not included in the list of known gitserver shards, will not delete repos"
            );
        }

        let jobs = self.jobs();
        let mut repos = Vec::new();
        fs::for_each_repo(&self.repos_dir, |name, git_dir| {
            repos.push((name.to_owned(), git_dir.to_path_buf()));
            false
        });

        let mut repos_cleaned = 0usize;
        'repos: for (repo, git_dir) in &repos {
            for job in &jobs {
                // Check if the context has been canceled; skip the rest.
                if shutdown.is_cancelled() {
                    tracing::warn!("aborting janitor run");
                    break 'repos;
                }
                let job_start = Instant::now();
                let (done, err) = self.run_job(job, &mut state, repo, git_dir).await;
                metrics::janitor_job_duration(
                    err.is_none(),
                    job,
                    job_start.elapsed().as_secs_f64(),
                );
                if let Some(err) = err {
                    tracing::error!(
                        name = %job,
                        repo = %git_dir.display(),
                        error = %err.message(),
                        "error running cleanup command"
                    );
                }
                if done {
                    break;
                }
            }
            repos_cleaned += 1;
            if repos_cleaned % 1000 == 0 {
                tracing::info!(repos_cleaned, "Janitor progress");
            }
        }

        if !state.repo_to_size.is_empty() {
            if let Some(store) = &self.store {
                match store.update_repo_sizes(&state.repo_to_size).await {
                    Ok(updated) => {
                        tracing::info!(
                            count = state.repo_to_size.len(),
                            updated,
                            "Updating repository sizes"
                        );
                    }
                    Err(err) => tracing::error!(error = %err, "setting repo sizes"),
                }
            }
        }

        // Set the gauges only at the end, when the totals are known.
        metrics::wrong_shard_repos(state.wrong_shard_count);
        if self.config.disable_delete_repos_on_wrong_shard {
            metrics::wrong_shard_repos_deleted(state.wrong_shard_deleted);
        }

        tracing::info!(
            duration = %crate::memobs::format_go_duration(start.elapsed()),
            "Janitor run finished"
        );
    }

    /// The ordered cleanup list from `cleanupRepos`.
    fn jobs(&self) -> Vec<&'static str> {
        let mut jobs = vec![
            "delete wrong shard repos",
            "maybe remove corrupt",
            "maybe remove non existing",
            "remove stale locks",
            "ensure git attributes",
            "auto gc config",
        ];
        match self.config.git_gc_mode {
            GcMode::JanitorAutoGc => jobs.push("garbage collect"),
            GcMode::Maintenance => {
                jobs.push("sg maintenance");
                jobs.push("git prune");
            }
            GcMode::GitAutoGc => {}
        }
        if !self.disable_auto_git_updates {
            jobs.push("maybe re-clone");
        }
        // Compute the size last so it reflects the previous jobs' cleanups.
        jobs.push("compute stats");
        jobs
    }

    async fn run_job(
        &self,
        name: &str,
        state: &mut RunState,
        repo: &str,
        git_dir: &Path,
    ) -> Outcome {
        match name {
            "delete wrong shard repos" => self.maybe_delete_wrong_shard(state, repo, git_dir),
            "maybe remove corrupt" => self.maybe_remove_corrupt(state, repo, git_dir).await,
            "maybe remove non existing" => {
                self.maybe_remove_non_existing(state, repo, git_dir).await
            }
            "remove stale locks" => remove_stale_locks(git_dir, self.long_command_timeout),
            "ensure git attributes" => (
                false,
                postfetch::set_git_attributes(git_dir)
                    .err()
                    .map(|err| GitError::Message(format!("setting git attributes: {err}"))),
            ),
            "auto gc config" => (
                false,
                postfetch::set_auto_gc(&GitRepo::new(git_dir), self.config.git_gc_mode)
                    .await
                    .err()
                    .map(|err| {
                        GitError::Message(format!("setting git gc mode: {}", err.message()))
                    }),
            ),
            "garbage collect" => (false, git_gc(git_dir).await.err()),
            "sg maintenance" => (false, self.sg_maintenance(git_dir).await.err()),
            "git prune" => (
                false,
                prune_if_needed(git_dir, self.config.loose_objects_limit)
                    .await
                    .err(),
            ),
            "maybe re-clone" => self.maybe_reclone(state, repo, git_dir).await,
            "compute stats" => collect_size(state, repo, git_dir),
            other => unreachable!("unknown janitor job {other}"),
        }
    }

    /// `maybeDeleteWrongShardRepos`.
    fn maybe_delete_wrong_shard(
        &self,
        state: &mut RunState,
        repo: &str,
        git_dir: &Path,
    ) -> Outcome {
        let addr = self
            .addresses
            .addr_for_repo(repo)
            .unwrap_or_default()
            .to_owned();
        if crate::addrs::hostname_match(&self.shard_id, &addr) {
            return (false, None);
        }
        state.wrong_shard_count += 1;

        // An unknown shard would consider almost every repo wrong; do not
        // empty the disk because of a configuration error.
        if !state.known_shard {
            return (false, None);
        }
        if self.config.disable_delete_repos_on_wrong_shard {
            return (false, None);
        }

        tracing::info!(
            dir = %git_dir.display(),
            target_shard = %addr,
            current_shard = %self.shard_id,
            "removing repo cloned on the wrong shard"
        );
        if let Err(err) = self.remove_repo(git_dir) {
            return (true, Some(err));
        }
        state.wrong_shard_deleted += 1;
        // We just deleted the repo; no further janitor tasks apply.
        (true, None)
    }

    /// `maybeRemoveCorrupt`.
    async fn maybe_remove_corrupt(
        &self,
        _state: &mut RunState,
        repo: &str,
        git_dir: &Path,
    ) -> Outcome {
        let (corrupt, should_log, reason, err) = check_repo_dir_corrupt(git_dir).await;
        if let Some(err) = err {
            return (false, Some(err));
        }
        if !corrupt {
            return (false, None);
        }
        if should_log {
            if let Some(store) = &self.store {
                if let Err(err) = store
                    .log_corruption(
                        repo,
                        &format!("sourcegraph detected corrupt repo: {reason}"),
                        &self.shard_id,
                    )
                    .await
                {
                    tracing::error!(repo, error = %err, "failed to log repo corruption");
                }
            }
        }
        tracing::warn!(
            repo = %git_dir.display(),
            reason,
            "removing corrupt repo"
        );
        if let Err(err) = self.remove_repo(git_dir) {
            return (true, Some(err));
        }
        metrics::repos_removed(reason);
        if let Some(store) = &self.store {
            if let Err(err) = store
                .set_clone_status(repo, CloneStatus::NotCloned, &self.shard_id)
                .await
            {
                return (
                    true,
                    Some(GitError::Message(format!(
                        "failed to update clone status: {err}"
                    ))),
                );
            }
        }
        (true, None)
    }

    /// `maybeRemoveNonExisting`: only active with `SRC_REMOVE_NON_EXISTING_REPOS`.
    async fn maybe_remove_non_existing(
        &self,
        _state: &mut RunState,
        repo: &str,
        git_dir: &Path,
    ) -> Outcome {
        if !self.config.remove_non_existing_repos {
            return (false, None);
        }
        let Some(store) = &self.store else {
            return (false, None);
        };
        match store.get_by_name(repo).await {
            // Repo still exists, nothing to do.
            Ok(Some(_)) => (false, None),
            // A failed DB lookup is not proof the repo is gone.
            Err(err) => {
                tracing::warn!(error = %err, repo, "failed to look up repo");
                (false, None)
            }
            Ok(None) => match self.remove_repo(git_dir) {
                Ok(()) => {
                    metrics::non_existing_repos_removed();
                    (true, None)
                }
                Err(err) => (true, Some(err)),
            },
        }
    }

    /// `maybeReclone`: remove (and thereby schedule a re-clone of) repos whose
    /// gc or `sg maintenance` failed too often.
    async fn maybe_reclone(&self, _state: &mut RunState, repo: &str, git_dir: &Path) -> Outcome {
        let mut reason = String::new();

        let gc_failed_times = match get_gc_fail_counter(git_dir) {
            Ok(count) => count,
            Err(err) => {
                return (
                    false,
                    Some(GitError::Message(format!(
                        "failed to read git GC failure counter: {err}"
                    ))),
                )
            }
        };
        if gc_failed_times >= GC_FAILURE_RECLONE_THRESHOLD {
            reason = "git gc failed too many times".to_owned();
            if let Ok(gc_log) = std::fs::read(git_dir.join("gc.log")) {
                if !gc_log.is_empty() {
                    reason = format!("{reason}: {}", String::from_utf8_lossy(trim_space(&gc_log)));
                }
            }
        }

        if self.config.sgm_retries >= 0
            && best_effort_read_failed(git_dir) > self.config.sgm_retries
        {
            if let Ok(sgm_log) = std::fs::read(git_dir.join(SGM_LOG)) {
                if !sgm_log.is_empty() {
                    reason = format!(
                        "sg maintenance, too many retries: {}",
                        String::from_utf8_lossy(trim_space(&sgm_log))
                    );
                }
            }
        }

        if reason.is_empty() {
            return (false, None);
        }

        // Converting a Perforce depot to Git is expensive; never reclone just
        // because it is old or slow to gc.
        let repo_type = match GitRepo::new(git_dir).config_get("sourcegraph.type").await {
            Ok(value) => value,
            Err(err) => return (false, Some(err)),
        };
        if repo_type == "perforce" {
            return (false, None);
        }

        tracing::info!(repo, reason, "re-cloning repo after GC failures");

        if let Err(err) = self.remove_repo(git_dir) {
            return (
                true,
                Some(GitError::Message(format!(
                    "failed to remove repo: {}",
                    err.message()
                ))),
            );
        }
        if let Some(store) = &self.store {
            if let Err(err) = store
                .set_clone_status(repo, CloneStatus::NotCloned, &self.shard_id)
                .await
            {
                return (
                    true,
                    Some(GitError::Message(format!(
                        "failed to update clone status: {err}"
                    ))),
                );
            }
        }
        metrics::repos_recloned();
        (true, None)
    }

    /// `fs.RemoveRepo`: atomic rename out of the tree, then delete.
    fn remove_repo(&self, git_dir: &Path) -> Result<(), GitError> {
        fs::remove_repo_directory(&self.repos_dir, git_dir)
            .map_err(|err| GitError::Message(err.to_string()))
    }
}

/// `removeStaleLocks`: delete lock files left behind by interrupted git
/// commands, using the baseline's conservative age thresholds.
fn remove_stale_locks(git_dir: &Path, long_command_timeout: Duration) -> Outcome {
    let mut errors: Vec<String> = Vec::new();
    fn record(errors: &mut Vec<String>, result: (bool, Option<std::io::Error>)) {
        if let Some(err) = result.1 {
            errors.push(err.to_string());
        }
    }

    // config.lock is held for a very short amount of time.
    record(
        &mut errors,
        remove_file_older_than(&git_dir.join("config.lock"), Duration::from_secs(60)),
    );
    // packed-refs can be held for quite a while; be conservative.
    record(
        &mut errors,
        remove_file_older_than(&git_dir.join("packed-refs.lock"), Duration::from_secs(3600)),
    );
    // Locks inside refs/ get the same conservative age.
    for path in walk_files(&git_dir.join("refs")) {
        if path.extension().is_some_and(|ext| ext == "lock") {
            record(
                &mut errors,
                remove_file_older_than(&path, Duration::from_secs(3600)),
            );
        }
    }
    // commit-graph.lock can block a repack; a 1h grace period is conservative.
    record(
        &mut errors,
        remove_file_older_than(
            &git_dir
                .join("objects")
                .join("info")
                .join("commit-graph.lock"),
            Duration::from_secs(3600),
        ),
    );
    // gc.pid is set by git gc and our sg maintenance script; 24h is twice
    // git's own stale threshold.
    let gc_pid_max_age = Duration::from_secs(24 * 3600);
    let (found_stale, error) = remove_file_older_than(&git_dir.join(GC_LOCK_FILE), gc_pid_max_age);
    if let Some(err) = error {
        errors.push(err.to_string());
    } else if found_stale {
        tracing::warn!(
            path = %git_dir.display(),
            age = %crate::memobs::format_go_duration(gc_pid_max_age),
            "removeStaleLocks found a stale gc.pid lockfile and removed it. This should not happen and points to a problem with garbage collection. Monitor the repo for possible corruption and verify if this error reoccurs"
        );
    }
    // Drop temporary pack files that a fetch can leave behind. The baseline
    // walks only the pack dir itself (`filepath.SkipDir` on subdirectories).
    let pack_dir = git_dir.join("objects").join("pack");
    if let Ok(entries) = std::fs::read_dir(&pack_dir) {
        for entry in entries.filter_map(Result::ok) {
            if entry
                .file_type()
                .map(|file_type| file_type.is_dir())
                .unwrap_or(false)
            {
                continue;
            }
            let name = entry.file_name();
            if !name.to_string_lossy().starts_with("tmp_pack_") {
                continue;
            }
            record(
                &mut errors,
                remove_file_older_than(&entry.path(), 2 * long_command_timeout),
            );
        }
    }

    if errors.is_empty() {
        (false, None)
    } else {
        (false, Some(GitError::Message(errors.join("\n"))))
    }
}

/// Every file below `root`, ignoring walk errors (`BestEffortWalk`).
fn walk_files(root: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.filter_map(Result::ok) {
            let Ok(file_type) = entry.file_type() else {
                continue;
            };
            let path = entry.path();
            if file_type.is_dir() {
                stack.push(path);
            } else {
                files.push(path);
            }
        }
    }
    files
}

/// `removeFileOlderThan`: remove `path` when its mtime is at least `max_age`
/// old. Returns whether a stale file was present and any removal error.
fn remove_file_older_than(path: &Path, max_age: Duration) -> (bool, Option<std::io::Error>) {
    let metadata = match std::fs::metadata(path) {
        Ok(metadata) => metadata,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return (false, None),
        Err(err) => return (false, Some(err)),
    };
    let Ok(modified) = metadata.modified() else {
        return (false, Some(std::io::Error::other("file has no mtime")));
    };
    // A future mtime yields an error from `duration_since`; the baseline's
    // negative age is also below `maxAge`.
    let too_old = SystemTime::now()
        .duration_since(modified)
        .map(|age| age >= max_age)
        .unwrap_or(false);
    if !too_old {
        return (false, None);
    }
    tracing::debug!(path = %path.display(), "removing stale lock file");
    match std::fs::remove_file(path) {
        Ok(()) => (true, None),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => (true, None),
        Err(err) => (true, Some(err)),
    }
}

/// `checkRepoDirCorrupt`: `(corrupt, shouldLog, reason, error)`.
async fn check_repo_dir_corrupt(git_dir: &Path) -> (bool, bool, &'static str, Option<GitError>) {
    // Both our cloning and fetching ensure there is a HEAD file.
    match std::fs::metadata(git_dir.join("HEAD")) {
        Ok(_) => {}
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            return (true, true, "missing-head", None)
        }
        Err(err) => {
            return (
                false,
                false,
                "",
                Some(GitError::Message(
                    repo_util::stat_error(&git_dir.join("HEAD"), err).to_string(),
                )),
            )
        }
    }

    if git_is_non_bare_best_effort(git_dir).await {
        return (true, true, "non-bare", None);
    }

    match check_repo_flagged_for_corruption(git_dir) {
        Ok(true) => {
            // The corruption was already logged by the git CLI side.
            (true, false, "failed-odb-read", None)
        }
        Ok(false) => (false, false, "", None),
        Err(err) => (false, false, "", Some(err)),
    }
}

/// `checkRepoFlaggedForCorruption`: stat and best-effort remove the magic
/// flag file written by `gitcli` when an object read failed.
fn check_repo_flagged_for_corruption(git_dir: &Path) -> Result<bool, GitError> {
    let path = git_dir.join(MAYBE_CORRUPT_FLAG);
    match std::fs::metadata(&path) {
        Ok(_) => {}
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(err) => {
            return Err(GitError::Message(
                repo_util::stat_error(&path, err).to_string(),
            ))
        }
    }
    // Best effort remove the flag; the next run re-flags it if needed.
    let _ = std::fs::remove_file(&path);
    Ok(true)
}

/// `gitIsNonBareBestEffort`: true only when git successfully answers `false`.
async fn git_is_non_bare_best_effort(git_dir: &Path) -> bool {
    let dir = git_dir.to_string_lossy().into_owned();
    let output = run_git(git_dir, &["-C", &dir, "rev-parse", "--is-bare-repository"]).await;
    let Ok(output) = output else {
        return false;
    };
    trim_space(&output.stdout) == b"false"
}

/// `gitGC`: `git gc --auto` with aggressive heuristics, tracking failures in
/// `gc.log` and `.sourcegraph-gc-fail-counter`.
async fn git_gc(git_dir: &Path) -> Result<(), GitError> {
    let args = [
        "-c",
        "gc.auto=1",
        "-c",
        "gc.autoDetach=false",
        "gc",
        "--auto",
    ];
    let output = run_git(git_dir, &args).await.map_err(|err| {
        GitError::Message(format!(
            "failed to git-gc: git git {} failed: {err}",
            args.join(" ")
        ))
    })?;
    if !output.status.success() {
        if let Ok(gc_log) = std::fs::read(git_dir.join("gc.log")) {
            if !gc_log.is_empty() {
                tracing::error!(
                    repo = %git_dir.display(),
                    gc_log = %String::from_utf8_lossy(&gc_log),
                    "git gc failed"
                );
                if let Err(err) = increment_gc_fail_counter(git_dir) {
                    tracing::error!(error = %err, "failed to increment git GC fail counter");
                }
            }
        }
        return Err(GitError::Message(format!(
            "failed to git-gc: {}",
            command_error_text("git", &args, &output)
        )));
    }
    // A successful run resets the failure counter.
    reset_gc_fail_counter(git_dir)
        .map_err(|err| GitError::Message(format!("failed to reset git GC fail counter: {err}")))
}

/// `sgMaintenance`: run the embedded script when `needsMaintenance` and no
/// recent `sgm.log` says otherwise.
impl Janitor {
    async fn sg_maintenance(&self, git_dir: &Path) -> Result<(), GitError> {
        // Skip when a recent failure is recorded; the error was already logged.
        if let Ok(metadata) = std::fs::metadata(git_dir.join(SGM_LOG)) {
            if let Ok(modified) = metadata.modified() {
                if modified > now_minus(self.config.sgm_log_expire) {
                    return Ok(());
                }
            }
        }

        let (needed, reason, error) = needs_maintenance(
            git_dir,
            self.config.auto_pack_limit,
            self.config.loose_objects_limit,
        );
        metrics::maintenance_status(error.is_none(), reason);
        if let Some(err) = error {
            return Err(err);
        }
        if !needed {
            return Ok(());
        }

        // Never run sg maintenance concurrently with git gc.
        let (lock, lock_error) = lock_repo_for_gc(git_dir);
        if let Some(err) = lock_error {
            tracing::debug!(
                dir = %git_dir.display(),
                error = %err.message(),
                "could not lock repository for sg maintenance"
            );
            return Ok(());
        }

        let output = run_maintenance_script(git_dir).await;
        drop(lock);
        // `unlock`: remove the gc.pid we created above.
        let _ = std::fs::remove_file(git_dir.join(GC_LOCK_FILE));
        let output = match output {
            Ok(output) => output,
            Err(err) => {
                return Err(GitError::Message(format!(
                    "failed to run sg maintenance: sh sh failed: {err}"
                )))
            }
        };
        if !output.status.success() {
            let combined = [output.stdout.as_slice(), output.stderr.as_slice()].concat();
            if let Err(err) = write_sgm_log(git_dir, &combined) {
                tracing::debug!(
                    file = %git_dir.join(SGM_LOG).display(),
                    error = %err,
                    "sg maintenance failed to write log file"
                );
            }
            tracing::debug!(
                dir = %git_dir.display(),
                out = %String::from_utf8_lossy(&combined),
                "sg maintenance"
            );
            return Err(GitError::Message(format!(
                "failed to run sg maintenance: {}",
                command_error_text("sh", &[], &output)
            )));
        }
        // Remove the log file after a successful run.
        let _ = std::fs::remove_file(git_dir.join(SGM_LOG));
        Ok(())
    }
}

async fn run_maintenance_script(git_dir: &Path) -> std::io::Result<std::process::Output> {
    let mut child = tokio::process::Command::new("sh")
        .current_dir(git_dir)
        .env("GIT_DIR", git_dir)
        .kill_on_drop(true)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    if let Some(mut stdin) = child.stdin.take() {
        use tokio::io::AsyncWriteExt as _;
        stdin.write_all(SG_MAINTENANCE_SCRIPT.as_bytes()).await?;
        drop(stdin);
    }
    child.wait_with_output().await
}

/// `lockRepoForGC`: create `gc.pid` exclusively. On failure, report the
/// process/machine already holding it when the file contains them.
fn lock_repo_for_gc(git_dir: &Path) -> (Option<std::fs::File>, Option<GitError>) {
    let path = git_dir.join(GC_LOCK_FILE);
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o644)
        .open(&path)
    {
        Ok(mut file) => {
            // git gc truncates the hostname to 256 bytes.
            let mut name = hostname();
            if name.len() > 256 {
                name = String::from_utf8_lossy(&name.as_bytes()[..256]).into_owned();
            }
            let _ = write!(file, "{} {}", std::process::id(), name);
            (Some(file), None)
        }
        Err(err) => {
            if let Ok(content) = std::fs::read(&path) {
                let text = String::from_utf8_lossy(&content);
                let mut parts = text.split(' ');
                if let (Some(pid), Some(machine)) = (parts.next(), parts.next()) {
                    return (
                        None,
                        Some(GitError::Message(format!(
                            "process {pid} on machine {machine} is already running a gc operation: {err}"
                        ))),
                    );
                }
            }
            (None, Some(GitError::Message(err.to_string())))
        }
    }
}

/// `pruneIfNeeded`: run `git prune --expire now` only when there are too many
/// loose objects.
async fn prune_if_needed(git_dir: &Path, limit: i64) -> Result<(), GitError> {
    let (needed, error) = too_many_loose_objects(git_dir, limit);
    metrics::prune_status(error.is_none(), !needed);
    if let Some(err) = error {
        return Err(err);
    }
    if !needed {
        return Ok(());
    }
    let args = ["prune", "--expire", "now"];
    let output = run_git(git_dir, &args).await.map_err(|err| {
        GitError::Message(format!(
            "failed to git-prune: git git {} failed: {err}",
            args.join(" ")
        ))
    })?;
    if !output.status.success() {
        return Err(GitError::Message(format!(
            "failed to git-prune: {}",
            command_error_text("git", &args, &output)
        )));
    }
    Ok(())
}

/// `needsMaintenance`: `(needed, reason, error)`; `reason` is `skipped` when
/// no maintenance is needed.
fn needs_maintenance(
    git_dir: &Path,
    auto_pack_limit: i64,
    loose_objects_limit: i64,
) -> (bool, &'static str, Option<GitError>) {
    match has_bitmap(git_dir) {
        Err(err) => return (false, "", Some(err)),
        Ok(false) => return (true, "bitmap", None),
        Ok(true) => {}
    }
    match has_commit_graph(git_dir) {
        Err(err) => return (false, "", Some(err)),
        Ok(false) => return (true, "commit_graph", None),
        Ok(true) => {}
    }
    match too_many_packfiles(git_dir, auto_pack_limit) {
        Err(err) => return (false, "", Some(err)),
        Ok(true) => return (true, "packfiles", None),
        Ok(false) => {}
    }
    match too_many_loose_objects(git_dir, loose_objects_limit) {
        (_, Some(err)) => return (false, "", Some(err)),
        (true, None) => return (true, "loose_objects", None),
        (false, None) => {}
    }
    (false, "skipped", None)
}

/// `hasBitmap`: `objects/pack/*.bitmap`.
fn has_bitmap(git_dir: &Path) -> Result<bool, GitError> {
    let pack_dir = git_dir.join("objects").join("pack");
    let entries = match std::fs::read_dir(&pack_dir) {
        Ok(entries) => entries,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(err) => {
            return Err(GitError::Message(format!(
                "reading {}: {err}",
                pack_dir.display()
            )))
        }
    };
    Ok(entries
        .filter_map(Result::ok)
        .any(|entry| entry.file_name().to_string_lossy().ends_with(".bitmap")))
}

/// `hasCommitGraph`: `objects/info/commit-graph`.
fn has_commit_graph(git_dir: &Path) -> Result<bool, GitError> {
    let path = git_dir.join("objects").join("info").join("commit-graph");
    match std::fs::metadata(&path) {
        Ok(_) => Ok(true),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(err) => Err(GitError::Message(
            repo_util::stat_error(&path, err).to_string(),
        )),
    }
}

/// `tooManyPackfiles`: count `objects/pack/*.pack` without a `.keep` sibling.
fn too_many_packfiles(git_dir: &Path, limit: i64) -> Result<bool, GitError> {
    let pack_dir = git_dir.join("objects").join("pack");
    let entries = match std::fs::read_dir(&pack_dir) {
        Ok(entries) => entries,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(err) => {
            return Err(GitError::Message(format!(
                "reading {}: {err}",
                pack_dir.display()
            )))
        }
    };
    let mut count: i64 = 0;
    for entry in entries.filter_map(Result::ok) {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let Some(stem) = name.strip_suffix(".pack") else {
            continue;
        };
        if pack_dir.join(format!("{stem}.keep")).exists() {
            continue;
        }
        count += 1;
    }
    Ok(count > limit)
}

/// `tooManyLooseObjects`: count `objects/17` files with hexadecimal names and
/// extrapolate to the 256 fan-out folders.
fn too_many_loose_objects(git_dir: &Path, limit: i64) -> (bool, Option<GitError>) {
    let dir = git_dir.join("objects").join("17");
    let entries = match std::fs::read_dir(&dir) {
        Ok(entries) => entries,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return (false, None),
        Err(err) => {
            return (
                false,
                Some(GitError::Message(format!("tooManyLooseObjects: {err}"))),
            )
        }
    };
    let mut count: i64 = 0;
    for entry in entries.filter_map(Result::ok) {
        // `reHexadecimal = ^[0-9a-f]+$`; directories do not count.
        if entry.file_type().map(|t| t.is_dir()).unwrap_or(false) {
            continue;
        }
        let name = entry.file_name();
        let bytes = name.as_encoded_bytes();
        if !bytes.is_empty()
            && bytes
                .iter()
                .all(|byte| matches!(byte, b'0'..=b'9' | b'a'..=b'f'))
        {
            count += 1;
        }
    }
    (count * 256 > limit, None)
}

/// `collectSize`: record the repository size at most once per day.
fn collect_size(state: &mut RunState, repo: &str, git_dir: &Path) -> Outcome {
    let last = match get_last_size_calculation(git_dir) {
        Ok(last) => last,
        Err(err) => return (false, Some(GitError::Message(err.to_string()))),
    };
    let recent = SystemTime::now()
        .duration_since(last)
        .map(|age| age < REPO_SIZE_RECALC_INTERVAL)
        // A future timestamp is also "recent" (negative age in Go).
        .unwrap_or(true);
    if recent {
        return (false, None);
    }
    let size = match fs::dir_size(git_dir) {
        Ok(size) => size,
        Err(err) => {
            return (
                false,
                Some(GitError::Message(format!("calculating repo size: {err}"))),
            )
        }
    };
    state.repo_to_size.push((repo.to_owned(), size));
    match set_last_size_calculation(git_dir, SystemTime::now()) {
        Ok(()) => (false, None),
        Err(err) => (false, Some(GitError::Message(err.to_string()))),
    }
}

/// `getLastSizeCalculation`: zero time when the file does not exist.
fn get_last_size_calculation(git_dir: &Path) -> std::io::Result<SystemTime> {
    let path = git_dir.join(LAST_SIZE_CALCULATION);
    match std::fs::metadata(&path) {
        Ok(metadata) => metadata.modified(),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(UNIX_EPOCH),
        Err(err) => Err(repo_util::stat_error(&path, err)),
    }
}

/// `setLastSizeCalculation`: create/truncate the file and set its mtime.
fn set_last_size_calculation(git_dir: &Path, when: SystemTime) -> std::io::Result<()> {
    let path = git_dir.join(LAST_SIZE_CALCULATION);
    let file = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(&path)?;
    file.set_times(std::fs::FileTimes::new().set_modified(when))
}

/// `getGCFailCounter`: a missing file is zero; invalid content is removed and
/// reported.
fn get_gc_fail_counter(git_dir: &Path) -> std::io::Result<i64> {
    let path = git_dir.join(GC_FAILED_COUNTER);
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(0),
        Err(err) => return Err(err),
    };
    match std::str::from_utf8(&bytes)
        .ok()
        .and_then(|text| text.parse::<i64>().ok())
    {
        Some(count) => Ok(count),
        None => {
            // Recover from invalid data by dropping the file.
            let _ = std::fs::remove_file(&path);
            Err(std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                "failed to parse the git GC fail counter",
            ))
        }
    }
}

/// `incrementGCFailCounter`.
fn increment_gc_fail_counter(git_dir: &Path) -> std::io::Result<()> {
    let current = get_gc_fail_counter(git_dir)?;
    std::fs::write(git_dir.join(GC_FAILED_COUNTER), (current + 1).to_string())
}

/// `resetGCFailCounter`.
fn reset_gc_fail_counter(git_dir: &Path) -> std::io::Result<()> {
    match std::fs::remove_file(git_dir.join(GC_FAILED_COUNTER)) {
        Ok(()) => Ok(()),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(err),
    }
}

/// `writeSGMLog`: `<header>\n\nfailed=<n+1>\n\n<output>\n`, mode 0600.
fn write_sgm_log(git_dir: &Path, output: &[u8]) -> std::io::Result<()> {
    let content = [
        SGM_LOG_HEADER.as_bytes(),
        b"\n\n",
        SGM_LOG_PREFIX.as_bytes(),
        (best_effort_read_failed(git_dir) + 1)
            .to_string()
            .as_bytes(),
        b"\n\n",
        output,
        b"\n",
    ]
    .concat();
    std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(git_dir.join(SGM_LOG))?
        .write_all(&content)
}

/// `bestEffortReadFailed`: the counter in `sgm.log`, or 0.
fn best_effort_read_failed(git_dir: &Path) -> i64 {
    match std::fs::read(git_dir.join(SGM_LOG)) {
        Ok(bytes) => best_effort_parse_failed(&bytes),
        Err(_) => 0,
    }
}

/// `bestEffortParseFailed`: parse the integer after `failed=` up to the next
/// newline.
fn best_effort_parse_failed(bytes: &[u8]) -> i64 {
    let prefix = SGM_LOG_PREFIX.as_bytes();
    let Some(from) = bytes
        .windows(prefix.len())
        .position(|window| window == prefix)
    else {
        return 0;
    };
    let mut rest = &bytes[from + prefix.len()..];
    if let Some(to) = rest.iter().position(|byte| *byte == b'\n') {
        if to > 0 {
            rest = &rest[..to];
        }
    }
    std::str::from_utf8(rest)
        .ok()
        .and_then(|text| text.parse::<i64>().ok())
        .unwrap_or(0)
}

/// `dir.Set(cmd)` + inherited environment for janitor git commands.
async fn run_git(git_dir: &Path, args: &[&str]) -> std::io::Result<std::process::Output> {
    tokio::process::Command::new("git")
        .args(args)
        .current_dir(git_dir)
        .env("GIT_DIR", git_dir)
        .kill_on_drop(true)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
        .await
}

/// `executil.WrapCmdError`: `<path> <args> failed with stderr: <stderr>` for a
/// non-zero exit, `<path> <args> failed` for a start error.
fn command_error_text(program: &str, args: &[&str], output: &std::process::Output) -> String {
    format!(
        "{program} {program} {} failed with stderr: {}",
        args.join(" "),
        String::from_utf8_lossy(&output.stderr)
    )
}

/// `hostname.Get()`: `HOSTNAME` when non-empty, otherwise the OS hostname.
fn hostname() -> String {
    match std::env::var("HOSTNAME") {
        Ok(name) if !name.is_empty() => name,
        _ => std::fs::read_to_string("/proc/sys/kernel/hostname")
            .map(|name| name.trim_end_matches('\n').to_owned())
            .unwrap_or_default(),
    }
}

fn now_minus(duration: Duration) -> SystemTime {
    let now = SystemTime::now();
    let nanos = now
        .duration_since(UNIX_EPOCH)
        .map(|since| since.as_nanos())
        .unwrap_or(0);
    let target = nanos.saturating_sub(duration.as_nanos());
    let target = u64::try_from(target).unwrap_or(u64::MAX);
    UNIX_EPOCH + Duration::from_nanos(target)
}

/// Go `bytes.TrimSpace` for the byte slices read from log files.
fn trim_space(bytes: &[u8]) -> &[u8] {
    let text = String::from_utf8_lossy(bytes);
    let trimmed = text.trim();
    // Only used for display; return the trimmed prefix of the original bytes
    // where possible.
    let start = text.len() - text.trim_start().len();
    let end = start + trimmed.len();
    &bytes[start.min(bytes.len())..end.min(bytes.len())]
}

