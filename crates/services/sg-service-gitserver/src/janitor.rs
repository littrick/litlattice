//! Port of `cmd/gitserver/internal/cleanup.go`: the periodic janitor that
//! removes wrong-shard and corrupt repositories, clears stale git locks,
//! keeps `info/attributes` and `gc.auto` in shape, runs garbage collection or
//! `sg maintenance`, and records repository sizes.
//!
//! The baseline runs this from `goroutine.NewPeriodicGoroutine`, which fires
//! immediately and then every `SRC_REPOS_JANITOR_INTERVAL` (default 1m). The
//! individual jobs are the closures in `cleanupRepos`, executed in order until
//! one reports `done` (the repo was deleted).
//!
//! Not covered here: the `wrexec` recording wrappers (they only record
//! commands for debug endpoints) and the per-command `ctx` plumbing.

use std::io::Write as _;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::Arc;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use sg_core::EnvReader;
